"""Deterministic coefficient export; run explicitly, never during CMake/build.
Python 3 / numpy2.3.5 scipy1.17.0. Source profile R0 §5, no C filter invocation.
"""
from pathlib import Path
import json, hashlib
import numpy as np
import scipy
from scipy import signal
p=Path(__file__).resolve().parent
h=signal.firwin(107,1333.3333333333333,fs=80000/3,window=('kaiser',7.85726))
q=np.rint(h*32768).astype(np.int64)
adjust=32768-int(q.sum());q[53]+=adjust # exact integer DC and retained symmetry
assert np.array_equal(q,q[::-1]) and q.sum()==32768 and np.max(np.abs(q))<32768
root=p.parent.parent
text='/* Generated by tests/dsp/generate_decim10.py; exact-DC Q15, R1 version1. */\n'
text+='#ifndef TR2_D10_COEFFICIENTS_H\n#define TR2_D10_COEFFICIENTS_H\n'
text+=f'#define TR2_D10_COEFF_L1 {sum(abs(int(x)) for x in q)}LL\n'
text+='static const int16_t tr2_d10_q15[107] = {\n'
text+='\n'.join('    '+', '.join(str(int(x)) for x in q[i:i+8])+',' for i in range(0,107,8))+'\n};\n#endif\n'
(root/'src/domain/acquisition/fir_decimator10_coefficients.h').write_text(text)
q31=np.rint(h*2**31).astype(np.int64);q31[53]+=2**31-int(q31.sum())
float32=h.astype(np.float32)
text='/* Test-only alternatives, generated independently from scipy.firwin. */\n#include <stdint.h>\n'
text+='static const int32_t d10_candidate_q31[107] = {\n'+',\n'.join(str(int(x)) for x in q31)+'\n};\n'
text+='static const float d10_candidate_f32[107] = {\n'+',\n'.join(float(x).hex()+'f' for x in float32)+'\n};\n'
(p/'decim10_candidates_coefficients.h').write_text(text)
manifest=dict(generator='scipy.signal.firwin(107,1333.3333333333333,fs=80000/3,window=(kaiser,7.85726))',numpy=np.__version__,scipy=scipy.__version__,q15_centre_adjustment=adjust,q15=[int(x) for x in q],q31=[int(x) for x in q31],float64=[float(x) for x in h],float32=[float(x) for x in float32],q15_l1=int(np.abs(q).sum()),q15_acc_bound=int(np.abs(q).sum())*32768,q15_raw_error_bound_counts=float(np.abs(q/32768-h).sum()*32768+1),hashes={})
for f in [root/'src/domain/acquisition/fir_decimator10_coefficients.h',p/'decim10_candidates_coefficients.h']:
 manifest['hashes'][f.relative_to(root).as_posix()]=hashlib.sha256(f.read_bytes()).hexdigest()
(p/'decim10_coefficients.json').write_text(json.dumps(manifest,indent=2)+'\n')
print('Q15 exact DC adjustment',adjust,'L1',manifest['q15_l1'],'accumulator bound',manifest['q15_acc_bound'],'raw difference bound incl two roundings',manifest['q15_raw_error_bound_counts'])
